/**
 * Regression: GPOS kerning stored in Extension Positioning lookups (lookupType 9), and in
 * several lookups of the kern feature.
 *
 * Upstream: issue #515 (EB Garamond of Google Fonts, "AV kerning should be -140, but
 * opentype.js returns 0") and PR #491 (Work Sans, no kerning value at all). In both fonts
 * the kern feature points to a lookup of type 9 whose subtables wrap Pair Adjustment
 * subtables (lookupType 2, PairPos format 1 for glyph pairs and format 2 for class pairs).
 * On upstream master getKerningTables keeps the lookups of type 2 only: font.getKerningValue
 * is 0 for A V in both fonts. The value records carry VariationIndex tables: their deltas
 * come from the item variation store of GDEF, at coordinates normalized through avar.
 *
 * Fixtures (how each one was built: test/fonts/regression/README.md):
 * - EBGaramond-VF-kern-subset.ttf (wght 400 to 800): the kern feature lists its lookups as
 *   [1, 0]. Lookup 0 is the extension lookup (format 1, format 1, format 2), lookup 1 is a plain
 *   lookup of type 2 (one format 2 subtable, coverage period and comma, kerning before a.01).
 *   No pair has a value in both lookups.
 *   Glyphs: 1 A, 2 L, 3 P, 4 T, 5 V, 6 X, 7 g, 8 j, 9 o, 11 y, 12 a.01 (not in the cmap),
 *   14 period, 15 comma, 16 colon, 17 hyphen.
 * - WorkSans-VF-kern-subset.ttf (wght 100 to 900, default 400): the only kern lookup is an
 *   extension lookup (format 1, format 1, format 2). GSUB has rvrn with FeatureVariations.
 *   Glyphs: 1 A, 2 L, 3 P, 4 T, 5 V, 6 o, 7 y, 8 period, 9 dollar, 10 dollar.BRACKET.202
 *   (not in the cmap).
 * - TestGPOS-KernTwoLookups.ttf (static, generated by test/generate-kern-lookups-font.py): the
 *   kern feature lists two lookups, [0, 1], that adjust the same pairs. Lookup 0 is a plain
 *   lookup of type 2, lookup 1 an extension lookup, each one with a format 1 and a format 2
 *   subtable. Glyphs: 2 A, 3 L, 4 T, 5 V, 6 o, 7 period.
 *
 * The reference values come from hb-shape (HarfBuzz 11.3.2), run in test/fonts/regression/.
 * The kerning of a pair is the advance of its left glyph minus the same advance with
 * --features=-kern. HarfBuzz applies every lookup of the feature, one after the other (the
 * values of two lookups for a pair add up), and in a lookup only the first subtable that
 * applies to the pair: a format 1 subtable that lists the pair, or a format 2 subtable that
 * covers its left glyph, even with a class record of 0. The scripts of GPOS have no language
 * system other than the default one (EB Garamond: DFLT, cyrl, grek, latn; Work Sans: DFLT, latn;
 * TestGPOS-KernTwoLookups.ttf: DFLT only), that HarfBuzz uses for any language, and HarfBuzz
 * uses DFLT for a script the font has not: its kerning depends neither on the language nor on
 * the script. The fork falls back the same way (see the tests of the text layout).
 */

