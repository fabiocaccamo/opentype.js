// a new font for each instance, by wght
function loadInstances(fixtureName, weights) {
    const fonts = {};
    for (const weight of weights) {
        fonts[weight] = loadFont(fixtureName, { wght: weight });
    }
    return fonts;
}

// compare a text with two lines of hb-shape: with kerning, and without (--features=-kern)
function assertKernedShape(font, text, expected, options) {
    const { glyphs, clusters, advances, advancesWithoutKerning } = expected;
    assertShape(shapeText(font, text, options), { glyphs, clusters, advances }, `"${text}" with kerning`);
    assertShape(
        shapeText(font, text, Object.assign({}, options, { kerning: false })),
        { glyphs, clusters, advances: advancesWithoutKerning },
        `"${text}" without kerning`
    );
}

// the two lines of hb-shape for "AVToTyLTP." at an instance of a font (see assertKernedShape)
function getClassPairsShape(reference, weight) {
    return {
        glyphs: reference.glyphs,
        clusters: classPairsClusters,
        advances: reference.advances[weight],
        advancesWithoutKerning: reference.advancesWithoutKerning[weight]
    };
}

function sum(values) {
    return values.reduce((total, value) => total + value, 0);
}

