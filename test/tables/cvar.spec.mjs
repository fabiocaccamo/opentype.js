import assert from 'assert';
import { parse } from '../../src/opentype.mjs';
import { getTableRecordOffset } from '../testutil.mjs';
import { readFileSync } from 'fs';
const loadSync = (url, opt) => parse(readFileSync(url), opt);

describe('tables/cvar.mjs', function() {
    const fonts = {
        cvarTest1: loadSync('./test/fonts/TestCVARGVAROne.ttf'),
        cvarTest2: loadSync('./test/fonts/TestCVARGVARTwo.ttf'),
    };
    // fontTools: varLib.instancer.instantiateVariableFont(font, {'wght': 142, 'wdth': 80, 'opsz': 36})['cvt '] of both
    // fonts, the deltas of the active tuples added up and rounded once
    const instanceCvt = [760, 10, 714, 0, 714, 10, 536, 10, 0, 0, 0, -10, 0, -10, -250, -10]
        .concat(Array(49).fill(0))
        .concat([80, 129, 85])
        .concat(Array(17).fill(0))
        .concat([38, 0, 62, 0, 0, 0, 0, 0, 34])
        .concat(Array(26).fill(0));
    it('correctly parses the tuple variation store', function() {
        // tests for all fonts
        for(const fontName in fonts) {
            const font = fonts[fontName];
            assert.deepEqual(font.tables.cvar.version, [1,0]);
            assert.equal(font.tables.cvar.headers.length, 11);
            assert.equal(font.tables.cvar.headers[0].peakTuple.length, font.tables.fvar.axes.length);
            assert.deepEqual(font.variation.process.getCvarTransform(), font.tables.cvt);
            assert.deepEqual(font.variation.process.getCvarTransform({wght: 142, wdth: 80, opsz: 36}), instanceCvt);
        };

        // one delta per point number of a tuple, like fontTools: [sum(1 for delta in variation.coordinates if delta is
        // not None) for variation in TTFont(path)['cvar'].variations] gives 6 for each tuple of both fonts
        [1].forEach(n => {
            const font = fonts[`cvarTest${n}`];
            assert.deepEqual(font.tables.cvar.headers.map(h => h.privatePoints),
                Array(11).fill([65,66,67,85,87,93]));
            assert.deepEqual(font.tables.cvar.headers.map(h => h.deltas.length),
            Array(11).fill(6));
        });
        [2].forEach(n => {
            const font = fonts[`cvarTest${n}`];
            assert.deepEqual(font.tables.cvar.sharedPoints, [65, 66, 67, 85, 87, 93]);
            assert.deepEqual(font.tables.cvar.headers.map(h => h.privatePoints),
                Array(11).fill(undefined));
            assert.deepEqual(font.tables.cvar.headers.map(h => h.deltas.length),
                Array(11).fill(6));
        });
    });

    describe('of tuples that vary all the cvt values', function() {
        // TestCVARAllPoints.ttf, generated by test/generate-cvar-all-points-font.py: 4 cvt values (100 200 300 400) and
        // two tuples without point numbers of their own (the packed point count 0, all the points) nor shared point
        // numbers, a delta for each cvt value. fontTools varLib.instancer.instantiateVariableFont(font, location)['cvt ']
        const instanceCvtByWeight = { 650: [105, 210, 315, 420], 250: [98, 196, 294, 392] };

        it('reads one delta for each cvt value', function() {
            const font = loadSync('./test/fonts/TestCVARAllPoints.ttf');
            assert.deepStrictEqual(font.tables.cvt, [100, 200, 300, 400]);
            assert.deepStrictEqual(font.tables.cvar.sharedPoints, []);
            assert.deepStrictEqual(font.tables.cvar.headers.map(header => [header.peakTuple, header.privatePoints, header.deltas]), [
                [[1], [], [10, 20, 30, 40]],
                [[-1], [], [-4, -8, -12, -16]]
            ]);
            for (const [weight, instanceCvt] of Object.entries(instanceCvtByWeight)) {
                assert.deepStrictEqual(font.variation.process.getCvarTransform({ wght: Number(weight) }), instanceCvt, weight);
            }
            assert.deepStrictEqual(font.warnings, []);
        });

        it('keeps the tuples before the first tuple variation header that does not fit in the table, with a warning', function() {
            // the tupleVariationCount (at 4 in the table) set from 2 to 0x0FFF: like gvar, HarfBuzz reads the headers up
            // to the first one that does not fit (tuple_iterator_t). The bytes after the 2 headers read as 2 headers
            // without an embedded peak, which a cvar tuple needs to be active (TupleVariationHeader::calculate_scalar),
            // then as a header of 10 bytes with an embedded peak and an intermediate region, past the end of the table:
            // the cvt values of fontTools varLib.instancer above
            const bytes = new Uint8Array(readFileSync('./test/fonts/TestCVARAllPoints.ttf'));
            const view = new DataView(bytes.buffer);
            const cvarOffset = view.getUint32(getTableRecordOffset(bytes, 'cvar') + 8);
            assert.strictEqual(view.getUint16(cvarOffset + 4), 2);
            view.setUint16(cvarOffset + 4, 0x0FFF);
            const font = parse(bytes.buffer);
            assert.deepStrictEqual(font.warnings.map(({ table, message }) => ({ table, message })), [{
                table: 'cvar',
                message: 'The tuples of the cvar table from the tuple 4 are skipped: Offset is outside the bounds of the DataView'
            }]);
            assert.ok(font.warnings[0].error instanceof RangeError);
            assert.deepStrictEqual(font.tables.cvar.headers.map(header => header.peakTuple), [[1], [-1], undefined, undefined]);
            for (const [weight, instanceCvt] of Object.entries(instanceCvtByWeight)) {
                assert.deepStrictEqual(font.variation.process.getCvarTransform({ wght: Number(weight) }), instanceCvt, weight);
            }
        });
    });

    it('does not vary the cvt table where a tuple whose data fail to parse applies, with a warning', function() {
        // TestCVARGVAROne.ttf with the variationDataSize of the last of its 11 tuples (peak wght -1, wdth -1, opsz 1; the
        // headers start at 8 in the table, 10 bytes each: 3 axes, embedded peaks) set to 0xFFFF, so that its data run
        // past the end of the table. Like gvar, HarfBuzz reads the data of a tuple only where it is active, and gives
        // no cvt delta where an active tuple fails to read (cvar::calculate_cvt_deltas returns false).
        const bytes = new Uint8Array(readFileSync('./test/fonts/TestCVARGVAROne.ttf'));
        const view = new DataView(bytes.buffer);
        const cvarOffset = view.getUint32(getTableRecordOffset(bytes, 'cvar') + 8);
        assert.strictEqual(view.getUint16(cvarOffset + 4) & 0x0FFF, 11);
        view.setUint16(cvarOffset + 8 + 10 * 10, 0xFFFF);
        const font = parse(bytes.buffer);
        // the tuple is inactive there and the other tuples vary the cvt values 65, 66, 67, 85, 87 and 93: the values of
        // fontTools varLib.instancer of the test above
        assert.deepStrictEqual(font.variation.process.getCvarTransform({ wght: 142, wdth: 80, opsz: 36 }), instanceCvt);
        assert.deepStrictEqual(font.warnings, []);
        assert.deepStrictEqual(font.variation.process.getCvarTransform({ wght: 28, wdth: 70, opsz: 72 }), font.tables.cvt);
        assert.deepStrictEqual(font.warnings.map(({ table, message }) => ({ table, message })), [{
            table: 'cvar',
            message: 'The cvt table is not varied where the tuple 10 applies: The serialized data of the tuple end past the end of the data'
        }]);
        assert.ok(font.warnings[0].error instanceof RangeError);
    });

    it('skips a table whose shared point numbers fail to parse after a header that does not fit, with its warning only', function() {
        // TestCVARGVAROne.ttf with the tupleVariationCount of its cvar table (at 4) set to 0x8FFF (shared point numbers,
        // 4095 tuples) and its dataOffset (at 6) to 0xFFFF: the bytes after the 11 headers of the table read as headers
        // up to one that does not fit (the tuple 34), and the shared point numbers at the dataOffset are past the end
        // of the table, so the table is skipped and
        // the tuples before the header that does not fit are not kept: HarfBuzz gives no cvt delta when the shared
        // point numbers fail to read (cvar::calculate_cvt_deltas returns false)
        const bytes = new Uint8Array(readFileSync('./test/fonts/TestCVARGVAROne.ttf'));
        const view = new DataView(bytes.buffer);
        const cvarOffset = view.getUint32(getTableRecordOffset(bytes, 'cvar') + 8);
        view.setUint16(cvarOffset + 4, 0x8FFF);
        view.setUint16(cvarOffset + 6, 0xFFFF);
        const font = parse(bytes.buffer);
        assert.deepStrictEqual(font.warnings.map(({ table, message }) => ({ table, message })), [{
            table: 'cvar',
            message: 'The table is skipped: Offset is outside the bounds of the DataView'
        }]);
        assert.strictEqual(font.tables.cvar, undefined);
        assert.deepStrictEqual(font.variation.process.getCvarTransform({ wght: 142, wdth: 80, opsz: 36 }), font.tables.cvt);
    });

    it('skips a table of another major version, like HarfBuzz', function() {
        // TestCVARGVAROne.ttf with the majorVersion of its cvar table set to 2: HarfBuzz does not read the table
        // (cvar::sanitize), and fontTools does not decompile it either
        const bytes = new Uint8Array(readFileSync('./test/fonts/TestCVARGVAROne.ttf'));
        const view = new DataView(bytes.buffer);
        view.setUint16(view.getUint32(getTableRecordOffset(bytes, 'cvar') + 8), 2);
        const font = parse(bytes.buffer);
        assert.deepStrictEqual(font.warnings.map(({ table, message }) => ({ table, message })), [{
            table: 'cvar',
            message: 'The table is skipped: Unsupported cvar table version 2.0'
        }]);
        assert.strictEqual(font.tables.cvar, undefined);
        assert.deepStrictEqual(font.variation.process.getCvarTransform({ wght: 142, wdth: 80, opsz: 36 }), font.tables.cvt);
    });

    it('reads a tuple without an embedded peak as inactive, like HarfBuzz', function() {
        // TestCVARGVAROne.ttf with the embedded peak flag of the tupleIndex of its last tuple (the tuple 10, peak wght -1,
        // wdth -1, opsz 1) cleared: a cvar tuple has no shared tuples, so HarfBuzz gives the scalar 0 to a tuple whose
        // peak is not embedded (TupleVariationHeader::calculate_scalar) and the other tuples still vary the cvt table.
        // fontTools: varLib.instancer.instantiateVariableFont(font, {'wght': 28, 'wdth': 70, 'opsz': 72})['cvt '] of
        // TestCVARGVAROne.ttf without the tuple 10 (del font['cvar'].variations[10])
        const bytes = new Uint8Array(readFileSync('./test/fonts/TestCVARGVAROne.ttf'));
        const view = new DataView(bytes.buffer);
        const tupleIndexOffset = view.getUint32(getTableRecordOffset(bytes, 'cvar') + 8) + 8 + 10 * 10 + 2;
        assert.strictEqual(view.getUint16(tupleIndexOffset) & 0x8000, 0x8000);
        view.setUint16(tupleIndexOffset, view.getUint16(tupleIndexOffset) & ~0x8000);
        const font = parse(bytes.buffer);
        assert.strictEqual(font.tables.cvar.headers[10].peakTuple, undefined);
        assert.deepStrictEqual(font.variation.process.getCvarTransform({ wght: 28, wdth: 70, opsz: 72 }),
            [760, 10, 714, 0, 714, 10, 536, 10, 0, 0, 0, -10, 0, -10, -250, -10]
                .concat(Array(49).fill(0))
                .concat([10, 28, 5])
                .concat(Array(17).fill(0))
                .concat([21, 0, 24, 0, 0, 0, 0, 0, 11])
                .concat(Array(26).fill(0))
        );
        assert.deepStrictEqual(font.warnings, []);
    });
});