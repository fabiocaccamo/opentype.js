import assert from 'assert';
import { Font, Path, Glyph, parse } from '../src/opentype.mjs';
import { readFileSync } from 'fs';
const loadSync = (url, opt) => parse(readFileSync(url), opt);

describe('opentype.mjs', function() {
    it('can load a TrueType font', function() {
        const font = loadSync('./test/fonts/Roboto-Black.ttf');
        assert.deepEqual(font.names.macintosh.fontFamily, {en: 'Roboto Black'});
        assert.deepEqual(font.names.windows.fontFamily, {en: 'Roboto Black'});
        assert.equal(font.unitsPerEm, 2048);
        assert.equal(font.glyphs.length, 1294);
        const aGlyph = font.charToGlyph('A');
        assert.equal(aGlyph.unicode, 65);
        assert.equal(aGlyph.path.commands.length, 15);
    });


    it('can load a OpenType/CFF font', function() {
        const font = loadSync('./test/fonts/FiraSansOT-Medium.otf');
        assert.deepEqual(font.names.macintosh.fontFamily, {en: 'Fira Sans OT Medium'});
        assert.deepEqual(font.names.windows.fontFamily, {en: 'Fira Sans OT Medium'});
        assert.equal(font.unitsPerEm, 1000);
        assert.equal(font.glyphs.length, 1151);
        const aGlyph = font.charToGlyph('A');
        assert.equal(aGlyph.name, 'A');
        assert.equal(aGlyph.unicode, 65);
        assert.equal(aGlyph.path.commands.length, 14);
    });

    it('can load a CID-keyed font', function() {
        const font = loadSync('./test/fonts/FDArrayTest257.otf');
        assert.deepEqual(font.names.windows.fontFamily, {en: 'FDArray Test 257'});
        assert.deepEqual(font.tables.cff.topDict.ros, ['Adobe', 'Identity', 0]);
        assert.equal(font.tables.cff.topDict._fdArray.length, 256);
        assert.equal(font.tables.cff.topDict._fdSelect[0], 0);
        assert.equal(font.tables.cff.topDict._fdSelect[42], 41);
        assert.equal(font.tables.cff.topDict._fdSelect[256], 255);
        assert.equal(font.unitsPerEm, 1000);
        assert.equal(font.glyphs.length, 257);
        const aGlyph = font.glyphs.get(2);
        assert.equal(aGlyph.name, 'cid00002');
        assert.equal(aGlyph.unicode, 1);
        assert.equal(aGlyph.path.commands.length, 24);
        assert.deepEqual(font.stringToGlyphIndexes('🌺'), [59]);
    });

    it('can load a WOFF/CFF font', function() {
        const font = loadSync('./test/fonts/FiraSansMedium.woff');
        assert.deepEqual(font.names.macintosh.fontFamily, {en: 'Fira Sans OT'});
        assert.deepEqual(font.names.windows.fontFamily, {en: 'Fira Sans OT'});
        assert.equal(font.unitsPerEm, 1000);
        assert.equal(font.glyphs.length, 1147);
        const aGlyph = font.charToGlyph('A');
        assert.equal(aGlyph.name, 'A');
        assert.equal(aGlyph.unicode, 65);
        assert.equal(aGlyph.path.commands.length, 14);
    });

    it('throws an error when advanceWidth is not set', function() {
        const notdefGlyph = new Glyph({
            name: '.notdef',
            unicode: 0,
            path: new Path()
        });
        const font = new Font({
            familyName: 'MyFont',
            styleName: 'Medium',
            unitsPerEm: 1000,
            ascender: 800,
            descender: -200,
            glyphs: [notdefGlyph]
        });
        assert.throws(function() { font.toArrayBuffer(); }, /advanceWidth is not a number/);
    });

    describe('the GDEF tables HarfBuzz ignores', function() {
        // fonts generated by test/generate-gdef-blocklist-fonts.py: quotedbl is a mark in GDEF, the kern lookup with
        // IgnoreMarks has pos A V -100, the calt lookup with IgnoreMarks has sub V' A by A; the GDEF, GSUB and GPOS
        // tables are 188, 248 and 3852 bytes long (a font of the blocklist of HarfBuzz) in TestGDEF-Blocklisted.ttf and
        // in its WOFF and WOFF2 fonts, 190, 248 and 3852 in TestGDEF-NotBlocklisted.ttf, 188, 250 and 3852 in
        // TestGDEF-NotBlocklistedGsubLength.ttf, 188, 248 and 3854 in TestGDEF-NotBlocklistedGposLength.ttf
        let blocklistedFont;
        let notBlocklistedFont;

        before(function() {
            blocklistedFont = loadSync('./test/fonts/TestGDEF-Blocklisted.ttf');
            notBlocklistedFont = loadSync('./test/fonts/TestGDEF-NotBlocklisted.ttf');
        });

        it('ignores the GDEF table of a font of the blocklist of HarfBuzz in the layout, so no glyph is a mark', function() {
            // hb-shape --no-glyph-names --cluster-level=1 TestGDEF-Blocklisted.ttf -u 0041,0022,0056
            // [1=0+500|3=1+500|2=2+500]
            assert.equal(blocklistedFont.getAdvanceWidth('A"V', 1000), 1500);
        });

        it('ignores the GDEF table of a font of the blocklist of HarfBuzz in the GSUB lookups', function() {
            // hb-shape --no-glyph-names --cluster-level=1 TestGDEF-Blocklisted.ttf -u 0056,0022,0041
            // [2=0+500|3=1+500|1=2+500]: quotedbl is not a mark, so V stays V
            assert.deepStrictEqual(blocklistedFont.stringToGlyphIndexes('V"A'), [2, 3, 1]);
            // hb-shape --no-glyph-names --cluster-level=1 TestGDEF-NotBlocklisted.ttf -u 0056,0022,0041
            // [1=0+500|3=1+0|1=2+500]: the calt lookup skips the mark and substitutes V by A
            assert.deepStrictEqual(notBlocklistedFont.stringToGlyphIndexes('V"A'), [1, 3, 1]);
        });

        it('still parses the GDEF table of a font of the blocklist of HarfBuzz', function() {
            // fontTools: TTFont('TestGDEF-Blocklisted.ttf')['GDEF'].table.GlyphClassDef.classDefs
            // {'A': 1, 'V': 1, 'quotedbl': 3}
            const classDef = blocklistedFont.tables.gdef.classDef;
            const glyphClasses = ['A', 'V', '"'].map(character =>
                blocklistedFont.substitution.getGlyphClass(classDef, blocklistedFont.charToGlyphIndex(character)));
            assert.deepStrictEqual(glyphClasses, [1, 1, 3]);
        });

        it('compares the lengths of the decompressed tables of a WOFF or WOFF2 font with the blocklist of HarfBuzz', function() {
            // the same tables as TestGDEF-Blocklisted.ttf, whose hb-shape output is above
            for (const fileName of ['TestGDEF-Blocklisted.woff', 'TestGDEF-Blocklisted.woff2']) {
                const compressedFont = loadSync(`./test/fonts/${fileName}`);
                assert.equal(compressedFont.getAdvanceWidth('A"V', 1000), 1500, fileName);
                assert.deepStrictEqual(compressedFont.stringToGlyphIndexes('V"A'), [2, 3, 1], fileName);
            }
        });

        it('reads the GDEF table of a font outside of the blocklist', function() {
            assert.notStrictEqual(notBlocklistedFont.tables.gdef, undefined);
            // hb-shape --no-glyph-names --cluster-level=1 TestGDEF-NotBlocklisted.ttf -u 0041,0022,0056
            // [1=0+400|3=1+0|2=2+500]: the A V -100 across the mark, at the origin of the mark (HarfBuzz also zeroes
            // the advance of the mark, which the fork does not do yet)
            const origins = [];
            notBlocklistedFont.forEachGlyph('A"V', 0, 0, 1000, {}, (glyph, glyphX) => origins.push(glyphX));
            assert.equal(origins[1], 400);
        });

        it('ignores the GDEF table of a font of the blocklist of HarfBuzz parsed with lowMemory', function() {
            // the hb-shape outputs of TestGDEF-Blocklisted.ttf and TestGDEF-NotBlocklisted.ttf above
            assert.equal(loadSync('./test/fonts/TestGDEF-Blocklisted.ttf', { lowMemory: true }).getAdvanceWidth('A"V', 1000), 1500);
            const origins = [];
            const lowMemoryFont = loadSync('./test/fonts/TestGDEF-NotBlocklisted.ttf', { lowMemory: true });
            lowMemoryFont.forEachGlyph('A"V', 0, 0, 1000, {}, (glyph, glyphX) => origins.push(glyphX));
            assert.equal(origins[1], 400);
        });

        it('compares the lengths of the GSUB and GPOS tables too with the blocklist of HarfBuzz', function() {
            // hb-shape --no-glyph-names --cluster-level=1 <font> -u 0041,0022,0056: [1=0+400|3=1+0|2=2+500], the
            // output of TestGDEF-NotBlocklisted.ttf: the A V -100 across the mark, at the origin of the mark
            for (const fileName of ['TestGDEF-NotBlocklistedGsubLength.ttf', 'TestGDEF-NotBlocklistedGposLength.ttf']) {
                const origins = [];
                loadSync(`./test/fonts/${fileName}`).forEachGlyph('A"V', 0, 0, 1000, {}, (glyph, glyphX) => origins.push(glyphX));
                assert.equal(origins[1], 400, fileName);
            }
        });
    });
});

