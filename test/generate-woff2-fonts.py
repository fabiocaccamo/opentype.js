"""Generates the WOFF2 fixtures of test/woff2.spec.mjs with fontTools.

Each source font of SOURCES is compressed into test/fonts/woff2/ with the
fontTools encoder, in every table transform it supports:

- <name>.glyf.woff2: glyf and loca transformed (the default of WOFF2)
- <name>.hmtx.woff2: glyf, loca and hmtx transformed
- <name>.null.woff2: no transform (glyf and loca stored as they are)

The CFF fonts have no glyf table: they get only <name>.fonttools.woff2.
The fixtures of the reference encoder of Google are generated by
generate-woff2-fonts-google.mjs.

Usage: python3 test/generate-woff2-fonts.py (requires fonttools and brotli)
"""

import os

from fontTools.ttLib import TTFont, woff2

FONTS_DIR = os.path.join(os.path.dirname(__file__), "fonts")
OUTPUT_DIR = os.path.join(FONTS_DIR, "woff2")

SOURCES = [
    # TrueType
    "Changa-Regular.ttf",  # hinted, composite glyphs
    "NotoSansThai-Medium-Testing-v1.ttf",  # composite glyphs, marks
    "sub5.ttf",
    # TrueType variable
    "VARTest.ttf",  # simple glyphs with the OVERLAP_SIMPLE flag
    "TestGVAR-Composite-0.ttf",  # variable composite glyphs
    "TestCVARGVAROne.ttf",  # instructions, cvar
    "TestTracking3.ttf",
    "TestHVARTwo.ttf",
    "Zycon.ttf",
    # CFF and CFF2
    "AbrilFatface-Regular.otf",
    "TestCMAP14.otf",
    "TestSVGmultiGlyphs.otf",
    "TestHVAROne.otf",
    "TestRVRN-CFF2.otf",
]

TRANSFORMS = {
    "glyf": {"glyf", "loca"},
    "hmtx": {"glyf", "loca", "hmtx"},
    "null": set(),
}


def main():
    os.makedirs(OUTPUT_DIR, exist_ok=True)
    for source in SOURCES:
        source_path = os.path.join(FONTS_DIR, source)
        name = os.path.splitext(source)[0]
        if "glyf" in TTFont(source_path):
            variants = TRANSFORMS
        else:
            variants = {"fonttools": None}
        for variant, transform_tables in variants.items():
            output_path = os.path.join(OUTPUT_DIR, f"{name}.{variant}.woff2")
            woff2.compress(source_path, output_path, transform_tables=transform_tables)
            print(output_path)


if __name__ == "__main__":
    main()
